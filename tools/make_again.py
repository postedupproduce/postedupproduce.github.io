def money(x):
    return ("$%.2f" % x).replace(".00", "")


def build(p):
    e = html.escape
    lines = "".join("<li>%s</li>" % e(l) for l in p["lines"])
    keep = '<p class="sub">%s</p>' % e(p["keep"]) if p.get("keep") else ""
    credit = ('<p class="credit">Your %s credit comes off what checkout shows.</p>' % money(p["credit"])
              if p["credit"] else "")
    data = {"slug": p["slug"], "box": p["box"], "bread": p["bread"], "qty": p["qty"], "mode": p["mode"],
            "stop": p["stop"], "note": (p["note"] + (" Apply %s credit." % money(p["credit"]) if p["credit"] else ""))}
    out = (TEMPLATE.replace("__FIRST__", e(p["first"])).replace("__SLUG__", p["slug"]).replace("__WHEN__", e(p["when"]))
           .replace("__LINES__", lines).replace("__KEEP__", keep).replace("__STOPLABEL__", e(STOP_LABEL[p["stop"]]))
           .replace("__CREDIT__", credit).replace("__DATA__", json.dumps(data)))
    assert "__" not in out.replace("__proto__", ""), "unfilled placeholder"
    d = os.path.join(ROOT, "p", p["slug"])
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "index.html"), "w") as f:
        f.write(out)
    return d


